"""Validate authored daily lessons and rebuild the browser bundle. Standard library only."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    curriculum = json.loads((ROOT / 'content/curriculum.json').read_text(encoding='utf-8'))
    courses = {}
    def pair(value):
        assert isinstance(value, list) and len(value) == 2 and all(isinstance(s, str) and s.strip() for s in value), 'Missing bilingual text'
    for course in ('spa', 'cruise', 'salon'):
        days = json.loads((ROOT / f'content/program-{course}.json').read_text(encoding='utf-8'))
        assert len(days) == 30 and [d['day'] for d in days] == list(range(1, 31)), f'{course}: expected days 1–30'
        valid = {m['id'] for m in curriculum['modules'][course]}
        assert {d['moduleId'] for d in days} == valid, f'{course}: chapter coverage'
        assert len({d['title'][0] for d in days}) == 30, f'{course}: repeated day titles'
        for d in days:
            assert d['moduleId'] in valid
            assert d['kind'] in ('lesson', 'checkpoint', 'capstone')
            for field in ('title', 'objective'):
                pair(d[field])
            for field in ('prompt', 'model'):
                pair(d['review'][field]); pair(d['practice'][field])
            assert len(d['teach']) == 2 and 2 <= len(d['dialogue']) <= 4
            for point in d['teach']:
                for field in ('title', 'body', 'example'):
                    pair(point[field])
            for turn in d['dialogue']:
                assert all(isinstance(turn[k], str) and turn[k].strip() for k in ('speaker', 'en', 'th'))
            assert len(d['practice']['criteria']) == 3
            for criterion in d['practice']['criteria']:
                pair(criterion)
            assert len(d['checks']) == 2
            for question in d['checks']:
                pair(question['question']); pair(question['explanation'])
                assert len(question['options']) == 3 and type(question['answer']) is int and 0 <= question['answer'] < 3
                for option in question['options']:
                    pair(option)
                assert len({option[0] for option in question['options']}) == 3
            if d['day'] in (7, 14, 21, 28, 29):
                assert d['kind'] == 'checkpoint'
            if d['day'] == 30:
                assert d['kind'] == 'capstone'
        courses[course] = days
    source = '/* Generated by tools/sync_daily_program.py from content/program-*.json. */\nconst DAILY_PROGRAM_DATA = ' + json.dumps(courses, ensure_ascii=False, separators=(',', ':')) + ';\n'
    (ROOT / 'js/daily-program-data.js').write_text(source, encoding='utf-8')
    print('Validated and bundled 90 bilingual daily lessons across 3 courses.')


if __name__ == '__main__':
    build()
